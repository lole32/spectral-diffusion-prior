"""
EnMAP + Sentinel-2 preprocessing with proper SRF and EnMAP downsampling.

- EnMAP is downsampled by a factor of 2 (array-level)
- Sentinel-2 remains at native 10m resolution
- Final ratio: 6 (1 EnMAP pixel = 6x6 S2 pixels)
- Output saved as MATLAB .mat file

Author: autogenerated
"""

import os
import argparse
import numpy as np
import rasterio
import scipy.io as sio
from scipy.ndimage import zoom


# ---------------------------------------------------------------------
# Argument parser
# ---------------------------------------------------------------------
def parse_args():
    parser = argparse.ArgumentParser(
        description="Prepare EnMAP + Sentinel-2 dataset with proper SRF and downsampling"
    )

    parser.add_argument(
        "--enmap_tif",
        type=str,
        required=True,
        help="Path to EnMAP spectral image GeoTIFF",
    )

    parser.add_argument(
        "--s2_tif",
        type=str,
        required=True,
        help="Path to Sentinel-2 native 10m GeoTIFF (4 bands)",
    )

    parser.add_argument(
        "--srf_mat",
        type=str,
        required=True,
        help="Path to proper SRF .mat file (R, enmap_wavelengths, s2_centers)",
    )

    parser.add_argument(
        "--output_dir",
        type=str,
        required=True,
        help="Directory where output .mat file will be saved",
    )

    parser.add_argument(
        "--downsample_factor",
        type=int,
        default=2,
        help="Downsampling factor for EnMAP (default: 2)",
    )

    parser.add_argument(
        "--crop_size_enmap",
        type=int,
        default=64,
        help="Crop size in EnMAP pixels after downsampling (default: 64)",
    )

    return parser.parse_args()


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------
def main():
    args = parse_args()

    ENMAP_TIF = args.enmap_tif
    S2_TIF = args.s2_tif
    SRF_PATH = args.srf_mat
    OUTPUT_DIR = args.output_dir

    DOWNSAMPLE_FACTOR = args.downsample_factor
    CROP_SIZE_ENMAP = args.crop_size_enmap

    OUTPUT_MAT = os.path.join(
        OUTPUT_DIR, "enmap_s2_data_r6.mat"
    )

    S2_10M_BANDS = [1, 2, 3, 4]
    NODATA_VALUE = -32768
    RATIO = 6

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    print("=" * 70)
    print("EnMAP + Sentinel-2 preprocessing with proper SRF and downsampling")
    print("=" * 70)

    # -----------------------------------------------------------------
    # 1. Load proper SRF
    # -----------------------------------------------------------------
    print("\n[1/10] Loading proper SRF")
    srf_data = sio.loadmat(SRF_PATH)

    R_proper = srf_data["R"]
    enmap_wavelengths = srf_data["enmap_wavelengths"].flatten()
    s2_centers = srf_data["s2_centers"].flatten()

    print(f"SRF shape: {R_proper.shape}")
    print(f"EnMAP wavelengths range: {enmap_wavelengths.min():.0f} - {enmap_wavelengths.max():.0f} nm")
    print(f"S2 band centers: {s2_centers}")

    for i in range(R_proper.shape[0]):
        peak_band = np.argmax(R_proper[i])
        peak_wl = enmap_wavelengths[peak_band]
        print(f"S2 band {i}: peak response at {peak_wl:.1f} nm")

    # -----------------------------------------------------------------
    # 2. Load EnMAP
    # -----------------------------------------------------------------
    print("\n[2/10] Loading EnMAP")
    with rasterio.open(ENMAP_TIF) as src:
        enmap = src.read().astype(np.float32)
        print(f"Original EnMAP shape: {enmap.shape}")
        print(f"NoData value: {src.nodata}")

    # -----------------------------------------------------------------
    # 3. Downsample EnMAP
    # -----------------------------------------------------------------
    print(f"\n[3/10] Downsampling EnMAP by factor {DOWNSAMPLE_FACTOR}")
    n_bands, h_orig, w_orig = enmap.shape

    enmap_mask_orig = (
        (enmap == NODATA_VALUE)
        | np.isnan(enmap)
        | np.isinf(enmap)
    )

    enmap_safe = np.where(enmap_mask_orig, 0, enmap)

    zoom_factor = (1, 1 / DOWNSAMPLE_FACTOR, 1 / DOWNSAMPLE_FACTOR)
    enmap_ds = zoom(enmap_safe, zoom_factor, order=1)

    mask_ds = zoom(enmap_mask_orig.astype(float), zoom_factor, order=0) > 0.5
    enmap_ds = np.where(mask_ds, np.nan, enmap_ds)

    print(f"Downsampled EnMAP shape: {enmap_ds.shape}")
    enmap = enmap_ds

    # -----------------------------------------------------------------
    # 4. Load Sentinel-2 (10m bands only)
    # -----------------------------------------------------------------
    print("\n[4/10] Loading Sentinel-2")
    with rasterio.open(S2_TIF) as src:
        if src.count != 4:
            print(f"Warning: expected 4 bands, got {src.count}")

        s2_bands = []
        for idx in S2_10M_BANDS:
            s2_bands.append(src.read(idx).astype(np.float32))

    s2 = np.stack(s2_bands, axis=0)
    print(f"Sentinel-2 shape: {s2.shape}")

    # -----------------------------------------------------------------
    # 5. Mask NoData
    # -----------------------------------------------------------------
    print("\n[5/10] Masking NoData values")
    enmap_mask = np.isnan(enmap) | np.isinf(enmap)
    s2_mask = (s2 == NODATA_VALUE) | np.isnan(s2) | np.isinf(s2)

    enmap = np.where(enmap_mask, np.nan, enmap)
    s2 = np.where(s2_mask, np.nan, s2)

    print(f"EnMAP NoData percentage: {100 * np.mean(enmap_mask):.2f}%")
    print(f"S2 NoData percentage: {100 * np.mean(s2_mask):.2f}%")

    # -----------------------------------------------------------------
    # 6. Crop sizes
    # -----------------------------------------------------------------
    print("\n[6/10] Setting crop sizes")
    _, h_full, w_full = enmap.shape
    h = min(CROP_SIZE_ENMAP, h_full)
    w = min(CROP_SIZE_ENMAP, w_full)

    H = h * RATIO
    W = w * RATIO

    print(f"EnMAP crop: {h} x {w}")
    print(f"S2 crop: {H} x {W}")

    # -----------------------------------------------------------------
    # 7. Cropping
    # -----------------------------------------------------------------
    print("\n[7/10] Cropping images")
    row0 = (h_full - h) // 2
    col0 = (w_full - w) // 2
    enmap_crop = enmap[:, row0 : row0 + h, col0 : col0 + w]

    _, H_full, W_full = s2.shape
    row0_s2 = (H_full - H) // 2
    col0_s2 = (W_full - W) // 2
    s2_crop = s2[:, row0_s2 : row0_s2 + H, col0_s2 : col0_s2 + W]

    # -----------------------------------------------------------------
    # 8. Reshape
    # -----------------------------------------------------------------
    print("\n[8/10] Reshaping arrays")
    I_HS = np.moveaxis(enmap_crop, 0, -1)
    I_MS = np.moveaxis(s2_crop, 0, -1)

    print(f"I_HS shape: {I_HS.shape}")
    print(f"I_MS shape: {I_MS.shape}")

    # -----------------------------------------------------------------
    # 9. Normalize
    # -----------------------------------------------------------------
    print("\n[9/10] Normalizing to [0, 1]")
    if np.nanmax(I_HS) > 10:
        I_HS /= 10000.0
    if np.nanmax(I_MS) > 10:
        I_MS /= 10000.0

    I_HS = np.clip(I_HS, 0, 1)
    I_MS = np.clip(I_MS, 0, 1)

    I_HS = np.nan_to_num(I_HS, nan=0.0).astype(np.float32)
    I_MS = np.nan_to_num(I_MS, nan=0.0).astype(np.float32)

    # -----------------------------------------------------------------
    # 10. Validation
    # -----------------------------------------------------------------
    print("\n[10/10] Validation")
    assert not np.isnan(I_HS).any()
    assert not np.isnan(I_MS).any()
    assert I_HS.max() > 0
    assert I_MS.max() > 0

    print("Validation passed")

    # -----------------------------------------------------------------
    # Save
    # -----------------------------------------------------------------
    print("\nSaving output")
    sio.savemat(
        OUTPUT_MAT,
        {
            "I_HS": I_HS,
            "I_MS": I_MS,
            "R": R_proper.astype(np.float32),
        },
    )

    print(f"Saved to: {OUTPUT_MAT}")
    print("Preprocessing completed successfully")


if __name__ == "__main__":
    main()
